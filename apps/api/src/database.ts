import type { Pool, PoolClient } from 'pg';

/** Pool ou client de transação: os repositórios aceitam os dois. */
export type Queryable = Pool | PoolClient;

/** Executa `work` em uma transação, com COMMIT no sucesso e ROLLBACK em caso de erro. */
export async function withTransaction<T>(pool: Pool, work: (client: PoolClient) => Promise<T>): Promise<T> {
  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    const result = await work(client);
    await client.query('COMMIT');
    return result;
  } catch (error) {
    await client.query('ROLLBACK');
    throw error;
  } finally {
    client.release();
  }
}

export async function initializeDatabase(pool: Pool): Promise<void> {
  await pool.query(`
    CREATE TABLE IF NOT EXISTS rooms (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      number TEXT NOT NULL UNIQUE,
      capacity INTEGER NOT NULL CHECK (capacity > 0),
      daily_rate NUMERIC(10, 2) NOT NULL CHECK (daily_rate > 0),
      description TEXT NOT NULL DEFAULT '',
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    );
    CREATE TABLE IF NOT EXISTS reservations (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      room_id INTEGER NOT NULL REFERENCES rooms(id) ON DELETE RESTRICT,
      guest_name TEXT NOT NULL,
      guest_count INTEGER NOT NULL CHECK (guest_count > 0),
      check_in DATE NOT NULL,
      check_out DATE NOT NULL,
      notes TEXT NOT NULL DEFAULT '',
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
      CHECK (check_out > check_in)
    );
    CREATE INDEX IF NOT EXISTS reservations_room_dates
      ON reservations(room_id, check_in, check_out);
  `);
}
