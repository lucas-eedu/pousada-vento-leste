import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { test } from 'node:test';
import { Pool } from 'pg';
import { initializeDatabase } from './database.js';

test('cria quartos e reservas com chave estrangeira ativa', { skip: !process.env.DATABASE_URL && 'Defina DATABASE_URL para o PostgreSQL de teste' }, async () => {
  const pool = new Pool({ connectionString: process.env.DATABASE_URL });
  try {
    await initializeDatabase(pool);
    const client = await pool.connect();
    try {
      await client.query('BEGIN');
      const number = `teste-${randomUUID()}`;
      const room = await client.query<{ id: number }>(
        'INSERT INTO rooms (number, capacity, daily_rate) VALUES ($1, $2, $3) RETURNING id',
        [number, 2, 180]
      );
      const roomId = room.rows[0].id;
      await client.query(
        'INSERT INTO reservations (room_id, guest_name, guest_count, check_in, check_out) VALUES ($1, $2, $3, $4, $5)',
        [roomId, 'Maria', 2, '2026-11-01', '2026-11-03']
      );
      const reservations = await client.query<{ guest_name: string }>('SELECT guest_name FROM reservations WHERE room_id = $1', [roomId]);
      assert.equal(reservations.rows[0].guest_name, 'Maria');
      await assert.rejects(client.query(
        'INSERT INTO reservations (room_id, guest_name, guest_count, check_in, check_out) VALUES ($1, $2, $3, $4, $5)',
        [-1, 'João', 1, '2026-11-01', '2026-11-03']
      ), { code: '23503' });
    } finally {
      await client.query('ROLLBACK');
      client.release();
    }
  } finally {
    await pool.end();
  }
});

test('adiciona telefone e e-mail às reservas de um banco criado antes desses campos', { skip: !process.env.DATABASE_URL && 'Defina DATABASE_URL para o PostgreSQL de teste' }, async () => {
  // Esquema isolado com a tabela no formato antigo, como no banco já publicado.
  const schema = `migracao_${randomUUID().replaceAll('-', '')}`;
  const admin = new Pool({ connectionString: process.env.DATABASE_URL });
  await admin.query(`CREATE SCHEMA ${schema}`);
  const pool = new Pool({ connectionString: process.env.DATABASE_URL, options: `-c search_path=${schema}` });
  try {
    await pool.query(`
      CREATE TABLE rooms (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, number TEXT NOT NULL UNIQUE,
        capacity INTEGER NOT NULL, daily_rate NUMERIC(10, 2) NOT NULL, description TEXT NOT NULL DEFAULT '',
        created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP);
      CREATE TABLE reservations (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        room_id INTEGER NOT NULL REFERENCES rooms(id) ON DELETE RESTRICT, guest_name TEXT NOT NULL,
        guest_count INTEGER NOT NULL, check_in DATE NOT NULL, check_out DATE NOT NULL,
        notes TEXT NOT NULL DEFAULT '', created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP);
      INSERT INTO rooms (number, capacity, daily_rate) VALUES ('101', 2, 200);
      INSERT INTO reservations (room_id, guest_name, guest_count, check_in, check_out) VALUES (1, 'Antiga', 1, '2026-12-01', '2026-12-02');
    `);

    await initializeDatabase(pool);
    await initializeDatabase(pool); // pode rodar a cada início do servidor sem erro

    const { rows } = await pool.query<{ guest_phone: string; guest_email: string }>('SELECT guest_phone, guest_email FROM reservations');
    assert.deepEqual(rows, [{ guest_phone: '', guest_email: '' }]);
  } finally {
    await pool.end();
    await admin.query(`DROP SCHEMA ${schema} CASCADE`);
    await admin.end();
  }
});
